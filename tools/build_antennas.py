#!/usr/bin/env python3
"""Builds app/src/main/assets/antennas.js from data.gov.il 'אנטנות סלולריות פעילות'
(Ministry of Environmental Protection). ITM (EPSG:2039) -> WGS84 (3-parameter shift)."""
import json, math, sys, urllib.request, urllib.parse
RES = "8935c8e5-ec77-421f-af86-d970583195f8"
URL = f"https://data.gov.il/api/3/action/datastore_search?resource_id={RES}&limit=32000"
src = sys.argv[1] if len(sys.argv) > 1 else None
data = json.load(open(src, encoding="utf-8")) if src else json.load(urllib.request.urlopen(URL, timeout=120))
recs = data["result"]["records"]

a, f = 6378137.0, 1/298.257222101
e2 = 2*f - f*f; ep2 = e2/(1-e2)
lat0, lon0, k0, x0, y0 = math.radians(31.7343936111111), math.radians(35.2045169444444), 1.0000067, 219529.584, 626907.39
def mer(phi):
    e4, e6 = e2**2, e2**3
    return a*((1-e2/4-3*e4/64-5*e6/256)*phi-(3*e2/8+3*e4/32+45*e6/1024)*math.sin(2*phi)+(15*e4/256+45*e6/1024)*math.sin(4*phi)-(35*e6/3072)*math.sin(6*phi))
M0 = mer(lat0)
def itm2grs(E, N):
    M = M0 + (N - y0)/k0
    mu = M/(a*(1-e2/4-3*e2**2/64-5*e2**3/256))
    e1 = (1-math.sqrt(1-e2))/(1+math.sqrt(1-e2))
    p1 = mu+(3*e1/2-27*e1**3/32)*math.sin(2*mu)+(21*e1**2/16-55*e1**4/32)*math.sin(4*mu)+(151*e1**3/96)*math.sin(6*mu)+(1097*e1**4/512)*math.sin(8*mu)
    s, c, t = math.sin(p1), math.cos(p1), math.tan(p1)
    C1, T1 = ep2*c*c, t*t
    N1 = a/math.sqrt(1-e2*s*s); R1 = a*(1-e2)/(1-e2*s*s)**1.5
    D = (E - x0)/(N1*k0)
    lat = p1-(N1*t/R1)*(D*D/2-(5+3*T1+10*C1-4*C1*C1-9*ep2)*D**4/24+(61+90*T1+298*C1+45*T1*T1-252*ep2-3*C1*C1)*D**6/720)
    lon = lon0+(D-(1+2*T1+C1)*D**3/6+(5-2*C1+28*T1-3*C1*C1+8*ep2+24*T1*T1)*D**5/120)/c
    return lat, lon
def shift(lat, lon, dx=-24.0024, dy=-17.1032, dz=-17.8444):
    # GRS80 geocentric translation; WGS84 ellipsoid differs by <0.1 mm, ignored
    s, c = math.sin(lat), math.cos(lat); N = a/math.sqrt(1-e2*s*s)
    X, Y, Z = N*c*math.cos(lon)+dx, N*c*math.sin(lon)+dy, N*(1-e2)*s+dz
    p = math.hypot(X, Y); ph = math.atan2(Z, p*(1-e2))
    for _ in range(5):
        N = a/math.sqrt(1-e2*math.sin(ph)**2); ph = math.atan2(Z+e2*N*math.sin(ph), p)
    return math.degrees(ph), math.degrees(math.atan2(Y, X))

def idx(lst, v):
    if v not in lst: lst.append(v)
    return lst.index(v)
companies, types = [], []
rows, bad = [], 0
P = "http://documents.sviva.gov.il/"
def clean(v): return "" if v is None else str(v).strip()
def num(v): return None if v in (None, "") else round(float(v), 3)
for r in recs:
    x, y = r.get("X_ITM"), r.get("Y_ITM")
    if not x or not y: bad += 1; continue
    lat, lon = shift(*itm2grs(float(x), float(y)))
    if not (29 < lat < 34 and 34 < lon < 36.1): bad += 1; continue
    rows.append([round(lat, 5), round(lon, 5), idx(companies, clean(r["חברה"])), clean(r["מס' אתר"]), clean(r["עיר"]),
        clean(r["כתובת האתר"]), idx(types, clean(r["סוג אתר"])), " ".join(clean(r["טכנולוגיית שידור"]).replace("דור","").split()),
        clean(r["תאריך היתר הקמה"]), clean(r["תאריך היתר הפעלה"]), clean(r["בדיקה תקופתית אחרונה"]), clean(r["היתר קרינה"]),
        num(r["עוצמה מרבית תיאורטית בµW לסמר"]), num(r["תוצאה מירבית ב% ביחס לסף הבריאות"]),
        clean(r["תאור נקודה בה התקבלה תוצאה מירבית"]),
        clean(r["קובץ הקמה"]).replace(P, ""), clean(r["קובץ הפעלה"]).replace(P, "")])
out = {"source": "המשרד להגנת הסביבה — data.gov.il — אנטנות סלולריות פעילות", "count": len(rows),
  "fields": ["lat","lon","company","siteNo","city","address","type","gens","buildPermit","opPermit","lastTest","radPermit","powerUWcm2","pctOfLimit","maxPoint","buildDoc","opDoc"],
  "companies": companies, "types": types, "rows": rows}
js = "/* generated by tools/build_antennas.py */\nwindow.RT_ANTENNAS=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
open("app/src/main/assets/antennas.js", "w", encoding="utf-8").write(js)
print(len(rows), "rows, skipped", bad, "bytes", len(js)); print(companies); print(types)
print("sample", rows[1][:2], "(Herzliya expected ~32.16,34.80)")
